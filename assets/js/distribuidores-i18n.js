  var SUPPORTED = ["es", "en", "it", "fr", "pt"];

  function detectLang() {
    try {
      var q = new URLSearchParams(window.location.search).get("lang");
      if (q && SUPPORTED.indexOf(q.toLowerCase()) !== -1) return q.toLowerCase();
      var stored = window.localStorage.getItem("ledyvas-dist-lang");
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
      var nav = (navigator.language || "es").slice(0, 2).toLowerCase();
      if (SUPPORTED.indexOf(nav) !== -1) return nav;
    } catch (e) { /* noop */ }
    return "es";
  }

  var current = detectLang();

  function setLang(code) {
    if (SUPPORTED.indexOf(code) === -1) return;
    current = code;
    try { window.localStorage.setItem("ledyvas-dist-lang", code); } catch (e) {}
    var url = new URL(window.location.href);
    url.searchParams.set("lang", code);
    window.location.href = url.toString();
  }

  function t(key, vars) {
    var pack = DICT[current] || DICT.es;
    var s = pack[key] != null ? pack[key] : (DICT.es[key] != null ? DICT.es[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      });
    }
    return s;
  }

  window.DistI18n = {
    SUPPORTED: SUPPORTED,
    lang: function () { return current; },
    setLang: setLang,
    t: t
  };
